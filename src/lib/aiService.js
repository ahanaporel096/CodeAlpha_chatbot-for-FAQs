const STORAGE_KEY = 'smart_faq_ai_config'

export function getAIConfig() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (!raw) {
      return {
        provider: PROVIDERS.GEMINI,
        apiKey: '',
        model: DEFAULT_MODELS[PROVIDERS.GEMINI],
        enabled: false,
        useAsFallbackOnly: true, // If true, only triggers when FAQ confidence is low
        systemPrompt:
          'You are the official Smart Academic FAQ & Campus Advisor Assistant for the institution. You provide accurate, helpful, polite, and concise answers about admissions, courses, fees, scholarships, hostel life, campus facilities, and academic schedules.',
      }
    }
    return JSON.parse(raw)
  } catch (err) {
    console.error('Failed to parse AI config from localStorage', err)
    return {
      provider: PROVIDERS.GEMINI,
      apiKey: '',
      model: DEFAULT_MODELS[PROVIDERS.GEMINI],
      enabled: false,
      useAsFallbackOnly: true,
      systemPrompt: '',
    }
  }
}

export function saveAIConfig(config) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(config))
  } catch (err) {
    console.error('Failed to save AI config to localStorage', err)
  }
}

/**
 * Call Google Gemini API
 */
async function callGemini({ apiKey, model, messages, systemPrompt, faqContext }) {
  const modelName = model || 'gemini-1.5-flash'
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${encodeURIComponent(
    apiKey
  )}`

  // Format contents for Gemini
  const contents = []

  // Add system instruction / knowledge context as user/model priming or systemInstruction
  let enrichedSystemPrompt = systemPrompt || 'You are an academic advisor FAQ chatbot.'
  if (faqContext && faqContext.length > 0) {
    enrichedSystemPrompt += `\n\nReference Campus FAQs for context:\n${faqContext
      .map((f) => `Q: ${f.question}\nA: ${f.answer}`)
      .join('\n\n')}`
  }

  // Add previous conversation turns (limit to last 6 for brevity)
  const recentMessages = messages.slice(-6)
  for (const msg of recentMessages) {
    contents.push({
      role: msg.role === 'user' ? 'user' : 'model',
      parts: [{ text: msg.content }],
    })
  }

  const payload = {
    systemInstruction: {
      parts: [{ text: enrichedSystemPrompt }],
    },
    contents,
    generationConfig: {
      temperature: 0.4,
      maxOutputTokens: 800,
    },
  }

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}))
    throw new Error(
      errorData.error?.message || `Gemini API error (${res.status}: ${res.statusText})`
    )
  }

  const data = await res.json()
  const candidate = data.candidates?.[0]
  if (!candidate?.content?.parts?.[0]?.text) {
    throw new Error('No text generated by Gemini API.')
  }

  return candidate.content.parts[0].text
}

/**
 * Call Groq API (OpenAI Compatible)
 */
async function callGroq({ apiKey, model, messages, systemPrompt, faqContext }) {
  const modelName = model || 'llama-3.3-70b-versatile'
  const url = 'https://api.groq.com/openai/v1/chat/completions'

  let enrichedSystemPrompt = systemPrompt || 'You are an academic advisor FAQ chatbot.'
  if (faqContext && faqContext.length > 0) {
    enrichedSystemPrompt += `\n\nReference Campus FAQs for context:\n${faqContext
      .map((f) => `Q: ${f.question}\nA: ${f.answer}`)
      .join('\n\n')}`
  }

  const formattedMessages = [
    { role: 'system', content: enrichedSystemPrompt },
    ...messages.slice(-6).map((m) => ({
      role: m.role === 'user' ? 'user' : 'assistant',
      content: m.content,
    })),
  ]

  const res = await fetch(url, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${apiKey.trim()}`,
    },
    body: JSON.stringify({
      model: modelName,
      messages: formattedMessages,
      temperature: 0.4,
      max_tokens: 800,
    }),
  })

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}))
    throw new Error(
      errorData.error?.message || `Groq API error (${res.status}: ${res.statusText})`
    )
  }

  const data = await res.json()
  const answer = data.choices?.[0]?.message?.content
  if (!answer) {
    throw new Error('No response received from Groq API.')
  }

  return answer
}

/**
 * Unified AI dispatch function
 */
export async function generateAIResponse({ query, conversationHistory = [], faqContext = [] }) {
  const config = getAIConfig()
  if (!config.enabled || !config.apiKey) {
    return null
  }

  const messages = [...conversationHistory, { role: 'user', content: query }]

  try {
    let responseText = ''
    if (config.provider === PROVIDERS.GROQ) {
      responseText = await callGroq({
        apiKey: config.apiKey,
        model: config.model,
        messages,
        systemPrompt: config.systemPrompt,
        faqContext,
      })
    } else {
      responseText = await callGemini({
        apiKey: config.apiKey,
        model: config.model,
        messages,
        systemPrompt: config.systemPrompt,
        faqContext,
      })
    }

    return {
      text: responseText,
      provider: config.provider,
      model: config.model,
    }
  } catch (err) {
    console.error(`Error generating response from ${config.provider}:`, err)
    throw err
  }
}

/**
 * Test connection with a simple ping
 */
export async function testConnection(config) {
  const testMessages = [{ role: 'user', content: 'Hello! Respond with "OK" if you can hear me.' }]

  if (config.provider === PROVIDERS.GROQ) {
    return await callGroq({
      apiKey: config.apiKey,
      model: config.model,
      messages: testMessages,
      systemPrompt: 'Respond in 1-5 words confirming connection.',
    })
  } else {
    return await callGemini({
      apiKey: config.apiKey,
      model: config.model,
      messages: testMessages,
      systemPrompt: 'Respond in 1-5 words confirming connection.',
    })
  }
}
